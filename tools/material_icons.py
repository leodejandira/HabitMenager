    if not os.path.exists(path):
        missing.append(sym); continue
    svg = open(path).read()
    paths = re.findall(r'<path d="([^"]+)"', svg)
    body = "\n".join(f'        <path\n            android:fillColor="#FF000000"\n            android:pathData="{d}" />' for d in paths)
