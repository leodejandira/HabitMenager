#!/usr/bin/env python3
"""Generates values/strings.xml and values-pt-rBR/strings.xml from tools/strings.txt."""
import os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for n, line in enumerate(open(os.path.join(root, "tools/strings.txt"), encoding="utf-8"), 1):
    line = line.rstrip("\n")
    if not line.strip() or line.startswith("#"):
        continue
    parts = [p.strip() for p in line.split(" | ")]
    if len(parts) != 3:
        sys.exit(f"line {n}: expected 3 columns: {line}")
    rows.append(parts)
keys = [r[0] for r in rows]
dups = {k for k in keys if keys.count(k) > 1}
if dups:
    sys.exit(f"duplicate keys: {dups}")

def esc(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;")
    s = s.replace("\\'", "'").replace("'", "\\'")
    return s

def write(path, col, extra=""):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/gen_strings.py — edit tools/strings.txt -->", "<resources>"]
    if extra:
        out.append(extra)
    for r in rows:
        out.append(f'    <string name="{r[0]}">{esc(r[col])}</string>')
    out.append("</resources>")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")

write(os.path.join(root, "app/src/main/res/values/strings.xml"), 1)
write(os.path.join(root, "app/src/main/res/values-pt-rBR/strings.xml"), 2)
print(f"{len(rows)} strings")
